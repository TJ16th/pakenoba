//! パケノバの中核。画面や描画に依存しない計算をまとめる。
//!
//! - `template`: 型紙（パネルと折り線）と、厚みのある紙を折る・丸める計算。型（寸法から型紙を作る関数）もここ。
//! - `surface`: 面のつながり（折り線と合わせ目）と、立体の上で置く柄の割り振り。
//! - `check`: 型紙が箱として成り立つかの検査（閉じているか、開けられるか）。
//! - `math`: 最小限のベクトルと変換。
//! - `project`: 案件のファイル（`.pknb`）の読み書き。
//!
//! このソフトが出す型紙はデザイン確認用で、製造用のデータではない。

pub mod check;
pub mod math;
pub mod project;
pub mod surface;
pub mod template;
